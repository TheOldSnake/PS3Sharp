using PS3Sharp.Cell.Spu.Interpreter;
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;

namespace PS3Sharp.Cell.Spu
{
    [StructLayout(LayoutKind.Sequential)]
    internal struct SpuRegister
    {
        // Manual: The leftmost word of a register is called the preferred slot, used for scalar operations.
        internal const int PreferredSlot = 3;

        // Zero/Default register
        internal static SpuRegister Zero => default;

        // Actual storage
        private UInt128 _storage;

        // 128-bit helper
        internal readonly UInt128 Value128 => _storage;

        // Span helpers
        internal Span<byte> Bytes => MemoryMarshal.AsBytes(AsSpan());
        internal Span<sbyte> SBytes => MemoryMarshal.Cast<SpuRegister, sbyte>(AsSpan());

        internal Span<ushort> UShorts => MemoryMarshal.Cast<SpuRegister, ushort>(AsSpan());
        internal Span<short> Shorts => MemoryMarshal.Cast<SpuRegister, short>(AsSpan());

        internal Span<uint> UInts => MemoryMarshal.Cast<SpuRegister, uint>(AsSpan());
        internal Span<int> Ints => MemoryMarshal.Cast<SpuRegister, int>(AsSpan());
        internal Span<float> Floats => MemoryMarshal.Cast<SpuRegister, float>(AsSpan());

        internal Span<ulong> ULongs => MemoryMarshal.Cast<SpuRegister, ulong>(AsSpan());
        internal Span<long> Longs => MemoryMarshal.Cast<SpuRegister, long>(AsSpan());
        internal Span<double> Doubles => MemoryMarshal.Cast<SpuRegister, double>(AsSpan());

        // Use "ref this" instead of "ref Value128" to avoid the implicit null check, which I think is generated by instance field access.
        // Relies on SPURegister being exactly 16 bytes with sequential layout.
        private Span<SpuRegister> AsSpan() => MemoryMarshal.CreateSpan(ref this, 1);

        // Preferred slot helpers
        internal int ScalarValue => Ints[PreferredSlot];
        internal uint UScalarValue => UInts[PreferredSlot];

        // Creates the register from UInt128 value
        internal static SpuRegister Create(UInt128 value)
        {
            SpuRegister register = new()
            {
                _storage = value,
            };

            return register;
        }

        // Creates the register from 2 ulong values
        internal static SpuRegister Create(ulong upper, ulong lower)
        {
            SpuRegister register = new()
            {
                _storage = new(upper, lower),
            };

            return register;
        }

        // Creates the register and initializes the preferred slot with a value
        internal static SpuRegister CreateFromScalar(uint value)
        {
            SpuRegister register = Zero;
            register.UInts[PreferredSlot] = value;
            return register;
        }
    }

    [InlineArray(128)]
    internal struct SpuRegisterArray
    {
        private SpuRegister _element;
    }
}
